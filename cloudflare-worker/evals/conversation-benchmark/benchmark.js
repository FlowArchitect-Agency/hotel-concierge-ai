function contextInteraction(suffix, reference) {
  if (['actually-correction'].includes(suffix)) return 'booking_request';
  if (['changed-mind'].includes(suffix)) return 'cancellation';
  if (reference === 'previous_request') return 'guest_request';
  if (reference === 'previous_question' || reference === 'topic_reset') return 'conversation';
  return 'hotel_service';
}

