const defaultClaims = ['booking_confirmed', 'availability_confirmed', 'staff_notified', 'invented_external_result'];

function turn(role, content) {
  return { role, content };
}

function scenario({
  id, title, category, language = 'en', severity = 'medium', guest_context = 'Anonymous website guest; no verified reservation details.',
  conversation, expected_semantics = {}, required_tools = [], allowed_tools = required_tools,
  expected_facts = [], forbidden_claims = defaultClaims, expected_language = language,
  requires_human = false, action_expectations = { mode: 'read_only', confirmation: 'prepared_or_unknown' },
  fixture = 'SUCCESS', notes = '', requires_llm_judge = ['context_relevance', 'naturalness', 'helpfulness'],
  critical_invariants = [],
}) {
  const required = [...new Set(required_tools)];
  const allowed = [...new Set(allowed_tools)];
  return {
    id,
    title,
    category,
    severity,
    language,
    guest_context,
    conversation,
    expected_semantics: {
      semantic_plan_valid: true,
      interaction_type: 'conversation',
      reference_target: 'none',
      topic_changed: false,
      ...expected_semantics,
    },
    required_tools: required,
    allowed_tools: allowed,
    forbidden_tools: BENCHMARK_TOOLS.filter((tool) => !allowed.includes(tool)),
    expected_facts,
    forbidden_claims,
    expected_language,
    requires_human,
    action_expectations,
    fixture,
    notes,
    requires_llm_judge,
    critical_invariants,
  };
}

function shortConversation(message, previous = 'How may I make your stay in Paris more enjoyable?') {
  return [turn('assistant', previous), turn('user', message)];
}

