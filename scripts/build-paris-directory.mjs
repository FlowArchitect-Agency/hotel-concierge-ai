// Builds cloudflare-worker/src/data/paris-directory.json from the concierge
// directory CSV. The CSV was compiled from model knowledge, not fetched, so
// only fields a guest can safely rely on are kept: phone numbers, opening hours
// and exact prices are dropped (the concierge confirms those), and any entry
// whose website does not answer at all is left out.
//
// Usage: node scripts/build-paris-directory.mjs <path/to/paris_concierge_directory.csv>
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2];
const OUT = new URL('../cloudflare-worker/src/data/paris-directory.js', import.meta.url);

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i += 1; } else if (ch === '"') quoted = false; else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i += 1;
      row.push(field); field = '';
      if (row.some((cell) => cell.trim())) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((cells) => Object.fromEntries(header.map((key, index) => [key.trim(), String(cells[index] ?? '').trim()])));
}

async function websiteAnswers(url) {
  // A guide page (not the venue's own site) proves nothing unless it loads:
  // the guide's bot wall answers 403 for real and invented slugs alike.
  const guidePage = /guide\.michelin\.com/i.test(url);
  for (const method of ['HEAD', 'GET']) {
    try {
      const response = await fetch(url, { method, redirect: 'follow', signal: AbortSignal.timeout(12_000), headers: { 'User-Agent': 'Mozilla/5.0 ConciergeFlow directory check' } });
      if (guidePage) {
        if (response.status < 400) return true;
        if (method === 'GET') return false;
        continue;
      }
      // Bot protection (403/405/429) still proves the site exists.
      if (response.status < 400 || [401, 403, 405, 429].includes(response.status)) return true;
      if (method === 'GET') return false;
    } catch {
      if (method === 'GET') return false;
    }
  }
  return false;
}

const rows = parseCsv(readFileSync(source, 'utf8').replace(/^﻿/, ''));
const seen = new Set();
const unique = rows.filter((row) => {
  const key = `${row.name}|${row.address}`.toLowerCase();
  if (!row.name || seen.has(key)) return false;
  seen.add(key);
  return true;
});

const dead = [];
const kept = [];
for (let i = 0; i < unique.length; i += 12) {
  const batch = unique.slice(i, i + 12);
  const checks = await Promise.all(batch.map((row) => (row.website ? websiteAnswers(row.website) : false)));
  batch.forEach((row, index) => (checks[index] ? kept : dead).push(row));
}

const list = (value) => value.split(';').map((item) => item.trim()).filter(Boolean);
const entries = kept.map((row) => ({
  name: row.name,
  category: row.category,
  subcategory: row.subcategory,
  arrondissement: row.arrondissement,
  neighborhood: row.neighborhood,
  address: row.address,
  website: row.website,
  price_level: row.price_level,
  description: row.description,
  tags: list(row.tags),
  good_for: list(row.good_for),
  booking_required: row.booking_required,
}));

writeFileSync(OUT, `// Generated by scripts/build-paris-directory.mjs -- do not edit by hand.\nexport default ${JSON.stringify(entries, null, 1)};\n`);
console.log(`rows=${rows.length} unique=${unique.length} kept=${entries.length} dropped_no_website=${dead.length}`);
for (const row of dead) console.log(`  dropped: ${row.name} (${row.website})`);
